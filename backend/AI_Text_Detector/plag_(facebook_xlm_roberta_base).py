import torch
import torch.nn.functional as F

def detect_ai_text(text):
    model.eval()

    device = next(model.parameters()).device

    inputs = tokenizer(
        text,
        return_tensors="pt",
        truncation=True,
        max_length=512,
        padding=True
    )

    inputs = {key: value.to(device) for key, value in inputs.items()}

    with torch.no_grad():
        outputs = model(**inputs)
        probabilities = F.softmax(outputs.logits, dim=-1)[0]

    human_probability = probabilities[0].item()
    ai_probability = probabilities[1].item()

    prediction = "AI-generated" if ai_probability >= 0.5 else "Human-written"

    return {
        "prediction": prediction,
        "human_probability": round(human_probability * 100, 2),
        "ai_probability": round(ai_probability * 100, 2)
    }

